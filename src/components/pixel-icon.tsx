export type PixelIconName = keyof typeof pixels;

/** Original 12 × 12 pixel glyphs; labels belong to the surrounding control. */
export function PixelIcon({
  name,
  ...props
}: SVGProps<SVGSVGElement> & { name: PixelIconName }) {
  return (
    <svg
      {...props}
      className={`pixel-icon ${props.className ?? ""}`}
      viewBox="0 0 12 12"
      fill="currentColor"
      shapeRendering="crispEdges"
      aria-hidden="true"
      focusable="false"
    >
      {pixels[name].flatMap((row, y) =>
        [...row].flatMap((pixel, x) =>
          pixel === "1"
            ? [<rect key={`${x}-${y}`} x={x} y={y} width="1" height="1" />]
            : [],
        ),
      )}
    </svg>
  );
}
